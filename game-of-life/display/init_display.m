function fig_handle = init_display(grid_size)
  % INIT_DISPLAY Initialize the display window for Game of Life
  %
  % Usage: fig_handle = init_display(grid_size)
  %
  % Inputs:
  %   grid_size - Size of the grid [rows, cols] or scalar for square grid
  %
  % Outputs:
  %   fig_handle - Handle to the created figure
  %
  % Creates a figure window with appropriate settings for displaying
  % the Game of Life grid with generation counter and statistics.

  % Handle scalar input (square grid)
  if isscalar(grid_size)
    rows = grid_size;
    cols = grid_size;
  else
    rows = grid_size(1);
    cols = grid_size(2);
  endif

  % Create figure window
  fig_handle = figure('Name', 'Conway''s Game of Life', ...
                      'NumberTitle', 'off', ...
                      'MenuBar', 'none', ...
                      'ToolBar', 'none', ...
                      'Color', [0.1 0.1 0.1], ...
                      'Position', [100, 100, 800, 850]);
  
  % Create axes for the grid
  ax = axes('Parent', fig_handle, ...
            'Position', [0.05 0.12 0.9 0.8], ...
            'XTick', [], ...
            'YTick', [], ...
            'Box', 'on', ...
            'XLim', [0.5, cols+0.5], ...
            'YLim', [0.5, rows+0.5]);
  
  % Set axis properties for proper display
  axis equal;
  axis tight;
  
  % Create text area for generation counter (bottom left)
  uicontrol('Parent', fig_handle, ...
            'Style', 'text', ...
            'String', 'Generation: 0', ...
            'Units', 'normalized', ...
            'Position', [0.05 0.05 0.3 0.05], ...
            'BackgroundColor', [0.1 0.1 0.1], ...
            'ForegroundColor', [0.9 0.9 0.9], ...
            'FontSize', 12, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'Tag', 'GenerationCounter');
  
  % Create text area for population count (bottom center)
  uicontrol('Parent', fig_handle, ...
            'Style', 'text', ...
            'String', 'Population: 0', ...
            'Units', 'normalized', ...
            'Position', [0.35 0.05 0.3 0.05], ...
            'BackgroundColor', [0.1 0.1 0.1], ...
            'ForegroundColor', [0.9 0.9 0.9], ...
            'FontSize', 12, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'center', ...
            'Tag', 'PopulationCounter');
  
  % Create text area for status (bottom right)
  uicontrol('Parent', fig_handle, ...
            'Style', 'text', ...
            'String', 'Status: Paused', ...
            'Units', 'normalized', ...
            'Position', [0.65 0.05 0.3 0.05], ...
            'BackgroundColor', [0.1 0.1 0.1], ...
            'ForegroundColor', [1.0 0.8 0.0], ...
            'FontSize', 12, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'right', ...
            'Tag', 'StatusText');
  
  % Create title
  title('Conway''s Game of Life', ...
        'Color', [0.9 0.9 0.9], ...
        'FontSize', 16, ...
        'FontWeight', 'bold');
  
  % Make figure visible
  drawnow;
  
endfunction
